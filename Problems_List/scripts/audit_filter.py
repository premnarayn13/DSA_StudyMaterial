# Analyze the 291 GFG problems
matched_dups = []
removed_trivia = []
kept_standard = []

striver_title_map = {p['title'].lower(): p for p in striver_core}

for p in gfg_added:
    t_clean = p['title'].strip().lower()
    t_no_brackets = re.sub(r'\[.*?\]', '', t_clean).strip()
    
    # 1. Is it a duplicate of Striver core?
    if t_clean in GFG_TO_STRIVER_DUPLICATES or t_no_brackets in GFG_TO_STRIVER_DUPLICATES:
        striver_title = GFG_TO_STRIVER_DUPLICATES.get(t_clean) or GFG_TO_STRIVER_DUPLICATES.get(t_no_brackets)
        striver_p = striver_title_map.get(striver_title.lower())
        matched_dups.append((p, striver_p))
    elif t_clean in GFG_TO_REMOVE_TRIVIA or t_no_brackets in GFG_TO_REMOVE_TRIVIA:
        removed_trivia.append(p)
    else:
        kept_standard.append(p)

print(f"\nBreakdown of 291 GFG problems:")
print(f"1. Additional Duplicates to merge into Striver altUrls: {len(matched_dups)}")
print(f"2. Simple / Trivia / SPOJ problems to filter out: {len(removed_trivia)}")
print(f"3. High-Quality Standard DSA Template Problems to KEEP: {len(kept_standard)}")

print("\n--- High-Quality Standard Problems Kept (sample 30) ---")
for idx, p in enumerate(kept_standard[:30], 1):
    print(f"{idx:2d}. [{p['topic']}] {p['title']}")
